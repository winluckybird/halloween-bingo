import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dependency } from '../scripts/dependencies.mjs';
const { chromium } = dependency('playwright');
const { PDFDocument } = dependency('pdf-lib');
const out = new URL('../test-output/', import.meta.url);
const file = name => new URL(name, out).pathname.replace(/^\/([A-Z]:)/i, '$1');
await mkdir(out, { recursive: true });
const executablePath = process.env.BROWSER_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync);
const browser = await chromium.launch({ headless: true, ...(executablePath ? { executablePath } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
const page = await context.newPage();
const errors = [], badResponses = [];
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => { if (response.status() >= 400) badResponses.push(response.url()); });
await page.goto('http://localhost:4173', { waitUntil: 'networkidle' });
await page.screenshot({ path: file('desktop.png'), fullPage: true });
assert.equal(await page.title(), 'Free Printable Halloween Bingo Cards & Generator');
assert.equal(await page.locator('.hero-card svg').count(), 1);
assert.equal(await page.locator('#print-root .print-sheet').count(), 34);
const defaultDownload = page.waitForEvent('download');
await page.locator('.hero .default-download').click();
await (await defaultDownload).saveAs(file('default.pdf'));
assert.equal((await PDFDocument.load(await readFile(file('default.pdf')))).getPageCount(), 34);
const firstCard = await page.locator('#preview-paper').innerHTML();
await page.locator('#next').click();
assert.notEqual(firstCard, await page.locator('#preview-paper').innerHTML());
await page.locator('#previous').click();
assert.equal(firstCard, await page.locator('#preview-paper').innerHTML());
await page.locator('#view-all').click();
assert.equal(await page.locator('.thumbnail').count(), 30);
await page.locator('[data-page="29"]').click();
assert.equal(await page.locator('#page-select').inputValue(), '29');
await page.locator('#tab-calling').click();
assert.equal(await page.locator('#page-select option').count(), 3);
await page.locator('#tab-rules').click();
assert.ok((await page.locator('#preview-paper').textContent()).includes('Draw, show, and mark'));
await page.locator('#tab-cards').click();
await page.locator('#view-all').click();
for (const [count, grid, paper, color] of [[1, 3, 'a4', 'ink'], [20, 4, 'letter', 'color'], [50, 5, 'a4', 'ink']]) {
  await page.locator('#card-count').fill(String(count));
  await page.locator(`input[name=grid][value="${grid}"]`).check({ force: true });
  await page.locator(`input[name=paper][value="${paper}"]`).check({ force: true });
  await page.locator(`input[name=color][value="${color}"]`).check({ force: true });
  assert.ok(await page.locator('#download-pdf').isDisabled());
  await page.locator('#generate').click();
  await page.waitForFunction(() => !document.querySelector('#generate').disabled);
  assert.equal(await page.locator('#page-select option').count(), count);
  assert.equal((await page.locator('#preview-paper').textContent()).includes('FREE'), grid === 5);
  assert.ok((await page.locator('#preview-paper').innerHTML()).includes(`assets/icons/${color}/`));
  const pdfDownload = page.waitForEvent('download');
  await page.locator('#download-pdf').click();
  await (await pdfDownload).saveAs(file(`custom-${grid}.pdf`));
  const pdf = await PDFDocument.load(await readFile(file(`custom-${grid}.pdf`)));
  assert.equal(pdf.getPageCount(), await page.locator('#print-root .print-sheet').count());
  assert.equal(pdf.getPage(0).getWidth(), paper === 'a4' ? 595.28 : 612);
  await writeFile(file(`preview-text-${grid}.json`), JSON.stringify(await page.locator('#print-root svg').evaluateAll(nodes => nodes.map(n => n.textContent))));
  const printBytes = await page.pdf({ preferCSSPageSize: true, printBackground: true });
  await writeFile(file(`browser-print-${grid}.pdf`), printBytes);
  const printPdf = await PDFDocument.load(printBytes);
  assert.equal(printPdf.getPageCount(), pdf.getPageCount(), 'No extra or split print pages');
  assert.ok(Math.abs(printPdf.getPage(0).getWidth() - pdf.getPage(0).getWidth()) < 1);
}
await page.evaluate(() => { window.__printCount = 0; window.print = () => { window.__printCount++; }; });
await page.locator('#print').click();
await page.waitForFunction(() => window.__printCount === 1);
assert.equal(await page.locator('#print-root .print-sheet').count(), 54);
for (const count of [10, 20, 30]) {
  await page.locator(`[data-count="${count}"]`).click();
  assert.equal(await page.locator('#card-count').inputValue(), String(count));
}
await page.locator('input[name=grid][value="5"]').check({ force: true });
await page.locator('input[name=color][value="color"]').check({ force: true });
await page.locator('input[name=paper][value="letter"]').check({ force: true });
await page.locator('#generate').click();
await page.waitForFunction(() => !document.querySelector('#generate').disabled);
const before = await page.locator('#preview-paper').innerHTML();
await page.locator('#generate').click();
await page.waitForFunction(() => !document.querySelector('#generate').disabled);
assert.notEqual(before, await page.locator('#preview-paper').innerHTML());
for (const width of [320, 375, 390, 768]) {
  await page.setViewportSize({ width, height: 844 });
  const dimensions = await page.evaluate(() => ({ page: document.documentElement.scrollWidth, viewport: innerWidth }));
  assert.ok(dimensions.page <= dimensions.viewport, `No overflow at ${width}px: ${JSON.stringify(dimensions)}`);
}
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: file('mobile.png'), fullPage: true });
await page.locator('#card-count').fill('10');
await page.locator('#generate').click();
await page.waitForFunction(() => !document.querySelector('#generate').disabled);
assert.equal(await page.locator('#page-select option').count(), 10);
await page.locator('#tab-calling').focus();
await page.keyboard.press('ArrowRight');
assert.equal(await page.locator('#tab-rules').getAttribute('aria-selected'), 'true');
assert.deepEqual(errors, []);
assert.deepEqual(badResponses, []);
await browser.close();
console.log('Browser checks passed: downloads, pagination, tabs, gallery, regeneration, all settings, print invocation, 320/375/390/768px overflow, keyboard tabs, 54-page A4 print pagination, no JS/network errors.');
